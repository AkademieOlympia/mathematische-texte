def rat_entry(x: float) -> str:
    if abs(x) < 1e-15:
        return "0"
    if abs(x - 0.5) < 1e-12:
        return "(1 : Rat) / 2"
    if abs(x - 1.5) < 1e-12:
        return "(3 : Rat) / 2"
    raise ValueError(x)


def find_subinvariant(Ms: np.ndarray, vs: np.ndarray) -> tuple[np.ndarray, int, int]:
    best = None
    for scale in (100, 200, 500, 1000, 2000, 5000, 10000):
        vi = np.maximum(np.rint(vs * scale), 1).astype(int)
        Mv = Ms @ vi.astype(float)
        th = float((Mv / vi).max())
        for den in (10, 20, 50, 100, 200, 500, 1000, 2000, 5000):
            num = int(np.ceil(th * den - 1e-15))
            theta = num / den
            if np.all(Mv <= theta * vi + 1e-8):
                if best is None or theta < best[0]:
                    best = (theta, num, den, vi.copy())
    if best is None:
        raise RuntimeError("no subinvariant found")
    _, num, den, vi = best
    return vi, num, den


def main() -> int:
    stem = "h7_shift_L8_C8p0"
    d = json.loads((EXPORT / f"{stem}.json").read_text())
    M = np.array(d["M_w"], float)
    words = [int(n["word"], 2) for n in d["nodes"]]
    vals, vecs = np.linalg.eig(M)
    k = int(np.argmax(np.abs(vals)))
    rho = float(np.real(vals[k]))
    v = np.real(vecs[:, k])
    if v.min() < 0:
        v = -v
    v = np.maximum(v, 0.0)
    supp = np.where(v > 1e-10)[0]
    Ms = M[np.ix_(supp, supp)]
    vs = v[supp]
    vs = vs / vs.max()
    n = len(supp)

    # float Doob at rho on support
    Mt = (Ms * vs[None, :]) / (rho * vs[:, None])
    row_sums = Mt.sum(axis=1)

    vi, num, den = find_subinvariant(Ms, vs)
    theta = num / den
    assert np.all(Ms @ vi <= theta * vi + 1e-8)

    doob = {
        "claim": (
            "Phase C Doob/subinvariant export for C=8 L=8 support; "
            "theta>1 infrastructure certificate; not HasContractiveDoob; "
            "not a Collatz proof"
        ),
        "C": 8.0,
        "L": 8,
        "n_full": len(words),
        "n_support": n,
        "support_indices": supp.tolist(),
        "support_words": [words[i] for i in supp],
        "rho_float": rho,
        "doob_row_sums_float": {
            "min": float(row_sums.min()),
            "max": float(row_sums.max()),
            "mean": float(row_sums.mean()),
        },
        "subinvariant": {
            "theta_num": num,
            "theta_den": den,
            "theta": theta,
            "v": vi.tolist(),
            "implies": "rho <= 599/500",
            "theta_lt_1": False,
        },
        "epistemics": {
            "full_graph_reducible": True,
            "perron_zeros": int((v <= 1e-10).sum()),
            "golden_theta_lt_1": "open — not claimed for C=8",
        },
    }
    out_json = EXPORT / "doob_data_L8_C8.json"
    out_json.write_text(json.dumps(doob, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out_json}")
    print(f"support n={n} rho={rho:.6f} theta={num}/{den}={theta}")
    print(f"Doob float row sums in [{row_sums.min():.6e}, {row_sums.max():.6e}]")

    # Lean audit on support
    flat = ", ".join(rat_entry(float(Ms[i, j])) for i in range(n) for j in range(n))
    vbody = ", ".join(str(int(x)) for x in vi)
