from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path("/Users/thomashoffbauer/Projects/Kepler-Hurrwitz")
EXPORT = ROOT / "docs" / "exports"
LEAN_DIR = ROOT / "KeplerHurwitz" / "Collatz"


def word_to_nat(w: str) -> int:
    return int(w, 2)


def rat_lit(x: float) -> str:
    if abs(x) < 1e-15:
        return "0"
    if abs(x - 0.5) < 1e-12:
        return "(1 : Rat) / 2"
    if abs(x - 1.5) < 1e-12:
        return "(3 : Rat) / 2"
    raise ValueError(x)


def matrix_lit(M: np.ndarray, n: int) -> str:
    rows = []
    for i in range(n):
        ents = ", ".join(rat_lit(float(M[i, j])) for j in range(n))
        rows.append(ents)
    body = ";\n    ".join(rows)
    return f"!![\n    {body}\n  ]"


def emit_common_header() -> str:
    return """/-
Copyright (c) 2026 Kepler-Hurrwitz contributors.
Auto-generated by export_resonanz_lean_audit.py — do not hand-edit matrix blocks.

Phase A: JSON survivor list + shift rule ⇒ MwFromShift = MwJson over Rat.
Phase B: spectral witnesses (nilpotency / rho lower bound).
Epistemics: finite audit; not a Collatz proof.
-/

import Mathlib.Data.Matrix.Basic
import Mathlib.Data.Rat.Defs
import Mathlib.Tactic
namespace KeplerHurwitz.Collatz.ResonanzOperatorAudit
"""


def emit_shift_core(L: int) -> str:
    return f"""
open Matrix

/-- Word encoded MSB-first as Nat (`int(word,2)`). -/
abbrev WordNat := Nat

/-- `u[1:] = v[:-1]` for bitstrings of length {L}. -/
def shiftCompatible (u v : WordNat) : Bool :=
  decide (u % (2 ^ ({L} - 1)) = v / 2)

def shiftWeight (v : WordNat) : Rat :=
  if v % 2 = 0 then (1 : Rat) / 2 else (3 : Rat) / 2

def mwFromWords {{n : Nat}} (words : Fin n → WordNat) : Matrix (Fin n) (Fin n) Rat :=
  Matrix.of fun i j =>
    if shiftCompatible (words i) (words j) then shiftWeight (words j) else 0
"""


def find_c8_witness(M: np.ndarray) -> tuple[list[int], tuple[int, int]]:
    vals, vecs = np.linalg.eig(M)
    k = int(np.argmax(np.abs(vals)))
    v = np.real(vecs[:, k])
    if v.min() < 0:
        v = -v
    v = np.maximum(v, 0)
    v = v / v.max()
    for scale in (100, 200, 500):
        vi = np.rint(v * scale).astype(int)
        for num, den in ((11, 10), (6, 5), (7, 6)):
            lam = num / den
            diff = M @ vi.astype(float) - lam * vi
            if np.all(diff >= -1e-9) and (vi > 0).sum() > 0 and lam > 1:
                return vi.tolist(), (num, den)
    raise RuntimeError("no witness")


def emit_instance(stem: str, tag: str, nilpotent_k: int | None, with_rho_lower: bool) -> Path:
    d = json.loads((EXPORT / f"{stem}.json").read_text())
    nodes = d["nodes"]
    n = len(nodes)
    M = np.array(d["M_w"], float)
    words = [word_to_nat(nd["word"]) for nd in nodes]
    L = d["L"]
    C = d["C"]

    lines = [emit_common_header(), emit_shift_core(L)]
    lines.append(f"\n/-! ## Instance {tag}: C={C}, L={L}, n={n} -/\n")
    lines.append(f"def n_{tag} : Nat := {n}")
    word_body = ", ".join(str(w) for w in words)
    lines.append(f"def wordsArr_{tag} : Array WordNat := #[{word_body}]")
    lines.append(
        f"def words_{tag} : Fin {n} → WordNat :=\n"
        f"  fun i => wordsArr_{tag}[i.val]!"
    )
    flat = ", ".join(rat_lit(float(M[i, j])) for i in range(n) for j in range(n))
    lines.append(f"def MwJsonArr_{tag} : Array Rat := #[{flat}]")
    lines.append(
        f"def MwJson_{tag} : Matrix (Fin {n}) (Fin {n}) Rat :=\n"
        f"  Matrix.of fun i j => MwJsonArr_{tag}[i.val * {n} + j.val]!"
    )
    lines.append(
        f"def MwLean_{tag} : Matrix (Fin {n}) (Fin {n}) Rat :=\n"
        f"  mwFromWords words_{tag}"
    )
    lines.append(
        f"""
/-- Phase A: Lean shift reconstruction equals exported JSON matrix. -/
theorem Mw_identity_{tag} : MwLean_{tag} = MwJson_{tag} := by
  native_decide
"""
    )

    if nilpotent_k is not None:
        lines.append(
            f"""
/-- Phase B: acyclic shift — nilpotent of index ≤ {nilpotent_k}. -/
theorem Mw_nilpotent_{tag} :
    MwLean_{tag} ^ {nilpotent_k} = 0 := by
  rw [Mw_identity_{tag}]
  native_decide
"""
        )

    if with_rho_lower:
        vi, (num, den) = find_c8_witness(M)
        vbody = ", ".join(str(x) for x in vi)
        nz = next(i for i,x in enumerate(vi) if x != 0)
        lines.append(
            f"""
/-- Integer Perron-type lower witness (from numeric evec, cleared). -/
def rhoWitnessArr_{tag} : Array Nat := #[{vbody}]
def rhoWitness_{tag} : Fin {n} → Rat :=
  fun i => (rhoWitnessArr_{tag}[i.val]! : Rat)

/-- Phase B: Mv ≥ (11/10) v with v ≥ 0, v ≠ 0 ⇒ ρ(M) ≥ 11/10 > 1. -/
theorem Mw_rho_lower_{tag} :
    ∀ i : Fin {n},
      (MwLean_{tag}.mulVec rhoWitness_{tag}) i
        ≥ (({num} : Rat) / {den}) * rhoWitness_{tag} i := by
  rw [Mw_identity_{tag}]
  native_decide

theorem Mw_rho_gt_one_{tag} :
    ∃ v : Fin {n} → Rat, ∃ lam : Rat,
      lam > 1 ∧ (∃ i, v i ≠ 0) ∧
        ∀ i, (MwLean_{tag}.mulVec v) i ≥ lam * v i := by
  refine ⟨rhoWitness_{tag}, ({num} : Rat) / {den}, by norm_num, ?_, Mw_rho_lower_{tag}⟩
  · refine ⟨⟨{nz}, by decide⟩, ?_⟩
    native_decide
"""
        )
        # unweighted entropy gap proxy: row branching of adjacency ≤ something — optional
        A = (M > 0).astype(float)
        rhoA = float(np.max(np.abs(np.linalg.eigvals(A))))
        lines.append(
            f"""
/-- Companion fact (numeric freeze): unweighted shift rho(A)≈{rhoA:.4f}<2 while weighted rho>1. -/
def unweightedRhoApprox_{tag} : Rat := {int(rhoA * 1000)} / 1000
"""
        )

    lines.append("end KeplerHurwitz.Collatz.ResonanzOperatorAudit")
    out = LEAN_DIR / f"ResonanzOperatorAudit_{tag}.lean"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size} bytes)")
    return out


def main() -> int:
    emit_instance("h7_shift_L8_C8p0", "L8C8", nilpotent_k=None, with_rho_lower=True)
    emit_instance("h7_shift_L8_C10p0", "L8C10", nilpotent_k=8, with_rho_lower=False)
    # also refresh C12 tiny identity in same style
    emit_instance("h7_shift_L8_C12p0", "L8C12", nilpotent_k=2, with_rho_lower=False)
